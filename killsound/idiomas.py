actual = None
_traductor_qt = None


def del_sistema():
    """Idioma del sistema si la app lo tiene; si no, inglés."""
    cands = []
    try:
        from PySide6.QtCore import QLocale
        cands += QLocale.system().uiLanguages()
    except Exception:
        pass
    for v in ('LANGUAGE', 'LC_ALL', 'LC_MESSAGES', 'LANG'):
        if os.environ.get(v):
            cands.append(os.environ[v].split(':')[0])
    try:
        cands.append(locale.getlocale()[0] or '')
    except ValueError:
        pass
    for c in cands:
        c = c.replace('-', '_').split('.')[0]
        if c in CODIGOS:
            return c
        base = c.split('_')[0].lower()
        if base == 'zh':
            return 'zh_TW' if any(x in c for x in ('TW', 'HK', 'MO', 'Hant')) else 'zh_CN'
        if base == 'pt':
            return 'pt_BR'
        if base in CODIGOS:
            return base
    return 'en'


def poner(codigo):
    global actual
    actual = codigo if codigo in TEXTOS else 'en'
    return actual


def elegido():
    """El idioma en uso: el de la configuración o, si no hay, el del sistema."""
    if actual is None:
        from . import config
        poner(config.leer_config().get('idioma') or del_sistema())
    return actual


def t(clave, **datos):
    texto = TEXTOS[elegido()].get(clave) or TEXTOS['en'][clave]
    return texto.format(**datos) if datos else texto


def decimal(x):
    s = f'{x:.2f}'
    return s if elegido() in DECIMAL_PUNTO else s.replace('.', ',')


def traducir_qt(app, codigo):
    """Botones estándar de Qt (Sí/No, Cancelar…) en el mismo idioma."""
    global _traductor_qt
    from PySide6.QtCore import QLibraryInfo, QTranslator
    if _traductor_qt is not None:
        app.removeTranslator(_traductor_qt)
        _traductor_qt = None
    tr = QTranslator(app)
    rutas = [QLibraryInfo.path(QLibraryInfo.LibraryPath.TranslationsPath)]
    for ruta in rutas:
        if tr.load(f'qtbase_{codigo}', ruta) or tr.load(f'qtbase_{codigo.split("_")[0]}', ruta):
            app.installTranslator(tr)
            _traductor_qt = tr
            return True
    return False
